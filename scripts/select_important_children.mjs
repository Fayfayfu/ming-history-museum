const selected=[];
for(const p of all){
  let key=simplify(p.name);
  if(p.title==='寧國公主') key='宁国公主';
  if(p.title==='長平公主') key='长平公主';
  if(key.startsWith('朱文奎')) key='朱文奎';
  if(key.startsWith('朱氏误称朱徽娖')) key='长平公主';
  const entry=spec.get(key);
  if(!entry) continue;
  const [reason,summary,evaluation,score,confidence]=entry;
  const normalName=key==='宁国公主'||key==='长平公主'?key:key;
  selected.push({...p,name:normalName,importance_reason:reason,summary,evaluation,score,confidence});
}

await fs.writeFile('data/ming_children_important.json',JSON.stringify(selected,null,2),'utf8');
