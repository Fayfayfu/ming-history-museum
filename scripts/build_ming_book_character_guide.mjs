function normalize(name) {
  if (extra[name]) {
    const [office, time, summary, evaluation, confidence] = extra[name];
    return { name: name === '汪直_海商' ? '汪直（海商首领）' : name, office, time, summary, evaluation, confidence };
  }
  const person = coreByName.get(name);
  if (!person) throw new Error(`Missing person: ${name}`);
  let time = person.office_start || '';
  if (Array.isArray(time)) time = time.join('、');
  if (typeof time === 'number') time = `${time}年起`;
  if (!time) time = person.birth && person.death ? `${person.birth}—${person.death}` : '时代节点见事件栏';
  return {
    name: person.name,
    office: person.office,
    time,
    summary: person.summary,
    evaluation: person.evaluation,
    confidence: person.confidence,
  };
}

function personCardAdvice(sourceName, person) {
  const decision = productDecision[sourceName];
  if (decision) {
    const [, , reason] = decision;
    const [hasCard, recommendCard] = cardDecision[sourceName];
    return { hasCard, recommendCard, reason };
  }
  const categoryReason = person.office.includes('帝')
    ? '属于帝系与年代骨架，统治直接定义本阶段。'
    : `“${person.summary.split(/[；。]/)[0]}”已是本阶段的人物理解节点。`;
  if (coreByName.has(sourceName)) {
    return { hasCard: '是（人物馆正式卡）', recommendCard: '否（已有正式卡）', reason: categoryReason };
  }
  if (relationCardNames.has(sourceName)) {
    return { hasCard: '是（宗室关系卡）', recommendCard: '否（保留现有层级）', reason: categoryReason };
  }
  throw new Error(`Missing person-card decision: ${sourceName}`);
}

